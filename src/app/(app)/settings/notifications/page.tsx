import { getContext } from "@/server/context";
import { DEFAULT_NOTIFICATION_PREFS } from "@/server/setup";
import { saveNotificationPrefsAction } from "@/app/(app)/_actions/settings";
import { ActionForm } from "@/components/action-form";
import { Card, CardHeader, Field, Input, PageHeader, SubNav } from "@/components/ui";
import { SETTINGS_TABS } from "../tabs";
import { PushToggle } from "./push-toggle";

export const metadata = { title: "Notifications" };

export default async function NotificationSettingsPage() {
  const { prefs } = await getContext();
  const n = prefs?.notifications ?? DEFAULT_NOTIFICATION_PREFS;
  const box = (name: string, label: string, checked: boolean, hint?: string) => (
    <label key={name} className="flex min-h-12 items-start gap-3 text-sm"><input type="checkbox" name={name} defaultChecked={checked} className="mt-0.5 size-5 accent-[var(--primary)]" /><span>{label}{hint ? <span className="block text-xs text-muted">{hint}</span> : null}</span></label>
  );
  return (
    <>
      <PageHeader title="Notifications" subtitle="Few, useful, and never during quiet hours" />
      <SubNav items={SETTINGS_TABS} active="/settings/notifications" />
      <div className="grid gap-4 md:grid-cols-2">
        <Card>
          <CardHeader title="What to notify about" />
          <ActionForm action={saveNotificationPrefsAction} submitLabel="Save">
            {box("inApp", "In-app notifications", n.inApp, "Shown under the bell icon.")}
            {box("billReminders", "Bill and subscription reminders", n.billReminders, "Uses each item's 'remind days before'.")}
            {box("weeklyReview", "Weekly review reminder", n.weeklyReview, "Sunday evening.")}
            {box("dailyBriefing", "Daily briefing ready", n.dailyBriefing)}
            {box("browserPush", "Also send to this browser/phone (push)", n.browserPush, "Requires enabling push below on each device.")}
            <div className="grid grid-cols-3 gap-2">
              <Field label="Quiet from" htmlFor="qs"><Input id="qs" name="quietStart" type="time" defaultValue={n.quietStart} /></Field>
              <Field label="Quiet until" htmlFor="qe"><Input id="qe" name="quietEnd" type="time" defaultValue={n.quietEnd} /></Field>
              <Field label="Max per day" htmlFor="mx"><Input id="mx" name="maxPerDay" type="number" min={0} max={10} defaultValue={n.maxPerDay} /></Field>
            </div>
          </ActionForm>
        </Card>
        <Card>
          <CardHeader title="Push on this device" subtitle="Permission is requested only when you press the button" />
          <PushToggle vapidKey={process.env.NEXT_PUBLIC_VAPID_PUBLIC_KEY || null} />
          <p className="mt-3 text-xs text-subtle">Reminders are generated by the background worker. If the worker isn&apos;t running (for example, a sleeping laptop), scheduled reminders won&apos;t be sent. See the README for hosting requirements.</p>
        </Card>
      </div>
    </>
  );
}
