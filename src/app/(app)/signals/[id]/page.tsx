import Link from "next/link";
import { notFound } from "next/navigation";
import { ExternalLink } from "lucide-react";
import { getContext } from "@/server/context";
import { loadFinanceSnapshot } from "@/server/views";
import { loadStory } from "@/server/news";
import { bookmarks, learnedConcepts, relevanceData, relevanceNotes } from "@/server/signals-meta";
import { conceptById } from "@/lib/news/concepts";
import { formatLongDate, formatTime12, toLocalDate, toLocalTime } from "@/lib/dates";
import { Badge, Card, CardHeader, Notice } from "@/components/ui";
import { ActionButton } from "@/components/toast";
import { ConceptCard } from "@/components/concept-card";
import { toggleBookmarkAction } from "@/app/(app)/_actions/signals";
import { TOPICS } from "../tabs";
import { ExplainForm } from "./explain-form";

export const metadata = { title: "Story" };

const EFFECT_LABELS = { consumers: "Consumers", companies: "Companies", sectors: "Sectors", assetClasses: "Asset classes" } as const;

export default async function StoryPage({ params }: PageProps<"/signals/[id]">) {
  const { id } = await params;
  if (!/^[0-9a-f-]{36}$/.test(id)) notFound();
  const ctx = await getContext();
  const s = await loadStory(ctx.db, id);
  if (!s) notFound();
  const [marks, learned, fin] = await Promise.all([bookmarks(ctx), learnedConcepts(ctx), loadFinanceSnapshot(ctx)]);
  const mark = marks.find((m) => m.newsItemId === s.id);
  // AI-generated explainers are shown only to users who opted into AI features.
  const e = s.explainerSource === "ai" && (ctx.prefs?.aiDataUse ?? "off") === "off" ? null : s.explainer;
  const notes = e ? relevanceNotes(e.conceptIds, relevanceData(fin)) : [];
  const external = /^https?:\/\//.test(s.url);
  return (
    <article className="mx-auto max-w-2xl space-y-4">
      <Link href="/signals" className="inline-flex min-h-9 items-center text-sm text-muted hover:text-text">← Signals</Link>
      <header>
        <p className="flex flex-wrap items-center gap-1.5 text-xs text-muted">
          {s.isDemo ? <Badge tone="accent">Demonstration story: fictional</Badge> : null}
          <span>{TOPICS[s.topic] ?? s.topic}</span> · <span>{s.sourceName}</span>
        </p>
        <h1 className="mt-1 text-2xl font-bold leading-tight tracking-tight">{s.title}</h1>
        <p className="mt-1 text-xs text-subtle">
          Published {formatLongDate(toLocalDate(s.publishedAt, ctx.tz))}, {formatTime12(toLocalTime(s.publishedAt, ctx.tz))} IST
          {s.eventDate ? ` · event date ${formatLongDate(s.eventDate)}` : " · event date not stated by source"}
        </p>
        <div className="mt-3 flex flex-wrap gap-2">
          {external ? <a href={s.url} target="_blank" rel="noopener noreferrer nofollow" className="inline-flex min-h-10 items-center gap-1.5 rounded-xl bg-primary px-3 text-sm font-semibold text-primary-fg">Read the original <ExternalLink size={14} aria-hidden /></a> : null}
          <ActionButton action={toggleBookmarkAction.bind(null, s.id)}>{mark ? "Remove bookmark" : "Bookmark"}</ActionButton>
        </div>
      </header>

      {!e ? (
        <Card>
          {s.summary ? <p className="text-[15px]">{s.summary}</p> : null}
          <Notice tone="neutral" className="mt-3">No explainer is available for this story. Explanations are generated only when AI explanations are enabled in Settings and a provider key is configured; otherwise, read the original for details.</Notice>
        </Card>
      ) : (
        <>
          <Card>
            <p className="text-[15px] leading-relaxed">{e.summary}</p>
            <p className="mt-3 text-[15px] leading-relaxed"><strong>Why this matters: </strong>{e.whyItMatters}</p>
            <p className="mt-3 text-[11px] text-subtle">{s.explainerSource === "ai" ? "Explanation generated by AI from the source summary. Check the original before relying on it." : s.explainerSource === "editorial_demo" ? "Written for demonstration." : ""}</p>
          </Card>
          <Card>
            <CardHeader title="Reported facts" subtitle="What the source states" />
            <ul className="list-disc space-y-1 pl-5 text-sm">{e.reportedFacts.map((f) => <li key={f}>{f}</li>)}</ul>
          </Card>
          {e.interpretation.length ? (
            <Card>
              <CardHeader title="Interpretation" subtitle="Analysis, not fact" />
              <ul className="list-disc space-y-1 pl-5 text-sm">{e.interpretation.map((f) => <li key={f}>{f}</li>)}</ul>
            </Card>
          ) : null}
          <Card>
            <CardHeader title="Possible effects" subtitle="Hypothetical: what could follow, not what will" />
            <dl className="space-y-2 text-sm">
              {(Object.keys(EFFECT_LABELS) as Array<keyof typeof EFFECT_LABELS>).filter((k) => e.possibleEffects[k]).map((k) => (
                <div key={k}><dt className="font-semibold">{EFFECT_LABELS[k]}</dt><dd className="text-muted">{e.possibleEffects[k]}</dd></div>
              ))}
            </dl>
            <p className="mt-3 text-xs text-subtle">This is context for understanding, not a reason to buy or sell anything.</p>
          </Card>
          <Card>
            <CardHeader title="What remains uncertain" />
            <ul className="list-disc space-y-1 pl-5 text-sm">{e.uncertainties.map((f) => <li key={f}>{f}</li>)}</ul>
          </Card>
          {notes.length ? (
            <Card>
              <CardHeader title="Connection to your records" subtitle="Based only on what you've entered" />
              <ul className="list-disc space-y-1 pl-5 text-sm">{notes.map((n) => <li key={n}>{n}</li>)}</ul>
            </Card>
          ) : null}
          {e.glossary.length ? (
            <Card>
              <CardHeader title="Glossary" />
              <dl className="space-y-2 text-sm">{e.glossary.map((g) => <div key={g.term}><dt className="font-semibold">{g.term}</dt><dd className="text-muted">{g.definition}</dd></div>)}</dl>
            </Card>
          ) : null}
          {e.conceptIds.map((cid) => conceptById(cid)).filter(Boolean).map((c) => <ConceptCard key={c!.id} concept={c!} learned={learned.has(c!.id)} />)}
        </>
      )}
      <Card><ExplainForm newsId={s.id} initial={mark?.note ?? null} /></Card>
    </article>
  );
}
